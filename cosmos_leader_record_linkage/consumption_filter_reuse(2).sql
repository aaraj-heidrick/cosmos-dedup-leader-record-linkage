-- Read-only reproduction of V_COSMOS_SENIOR_LEADERSHIP_CONSUMPTION.
-- Extracted from live Snowflake definitions on 2026-10-08.
-- Existing canonical C-suite and qualified VP/President inputs are required.
-- To port: replace the TWO canonical input table references and supply the same
-- title, match-source, ROLE_TIER and CANONICAL_JOB_ID contracts. See REUSE_GUIDE.md.
-- This does not rebuild the upstream raw-posting canonicalization pipeline.
WITH high_precision AS (
WITH m AS (
    SELECT *, 'C_SUITE' AS ROLE_TIER, C_SUITE_MATCH_SOURCE_FIELD AS HSRC
    FROM PC_FIVETRAN_DB.DA_WORKSPACE.COSMOS_C_SUITE_CLEAN_CANONICAL_OUTPUT
    UNION ALL BY NAME
    SELECT *, SVP_PRES_MATCH_SOURCE_FIELD AS HSRC
    FROM PC_FIVETRAN_DB.DA_WORKSPACE.COSMOS_SVP_PRESIDENT_CLEAN_CANONICAL_OUTPUT
),
s AS (
    SELECT m.*,
        ' ' || REGEXP_REPLACE(UPPER(COALESCE(TITLE_RAW,'')||' '||COALESCE(TITLE_TRANSLATED,'')),'[^A-Z0-9]+',' ') || ' ' AS TXT2,
        ' ' || REGEXP_REPLACE(UPPER(COALESCE(TITLE_RAW,'')),'[^A-Z0-9]+',' ') || ' ' AS RAW2
    FROM m
),
e AS (
    SELECT s.*,
        CASE
            WHEN HSRC = 'TITLE_TRANSLATED' THEN 'TRANSLATED_ONLY'
            WHEN (REGEXP_LIKE(TXT2,'.* AVP .*') AND NOT REGEXP_LIKE(TXT2,'.* AREA VICE PRESIDENT .*'))
              OR REGEXP_LIKE(TXT2,'.* ASSOCIATE VICE PRESIDENT .*') OR REGEXP_LIKE(TXT2,'.* ASSISTANT VICE PRESIDENT .*')
              OR (REGEXP_LIKE(TXT2,'.* DVP .*') AND NOT REGEXP_LIKE(TXT2,'.* DIVISION VICE PRESIDENT .*'))
              OR REGEXP_LIKE(TXT2,'.* DEPUTY (CEO|CFO|COO|CTO|CIO|CMO|CHRO|CISO|VICE PRESIDENT|PRESIDENT) .*') THEN 'VP_FLOOR'
            WHEN REGEXP_LIKE(TXT2,'.* (EA TO|ASSISTANT|ASST|SECRETARY|PA TO|CHIEF OF STAFF|BUSINESS PARTNER|REPORTING TO|REPORTS TO|OFFICE OF THE PRESIDENT|OFFICE OF THE CEO|OFFICE OF THE COO|OFFICE OF THE CFO|OFFICE OF THE CHAIR|TO THE CEO|TO THE COO|TO THE CFO|TO THE PRESIDENT|TO CEO|TO COO|TO CFO|TO CIO|TO PRESIDENT|TO THE VP|TO SVP|TO EVP) .*') THEN 'SUPPORT'
            WHEN REGEXP_LIKE(TXT2,'.* (ELECTRICIEN|ELECTRICAL|ELECTRICITE|COURANT|TERTIAIRE) .*') THEN 'FRENCH_ELECTRICAL_CFO_CFA'
            WHEN REGEXP_LIKE(TXT2,'.* (DESSINATEUR|PROJETEUR|CONCEPTEUR|DAO|CAD) .*') THEN 'CAD_TECH_CAO_DAO'
            WHEN REGEXP_LIKE(TXT2,'.* (STRATEGIST|PLANNER|COMPUTER NETWORK|NETWORK OPERATIONS|CONSTRUCTION SAFETY|CREDIT MARKETING|PROTECTION OFFICER) .*') THEN 'ACRONYM_COLLISION'
            WHEN REGEXP_LIKE(RAW2,'.* (CDI|CFC) .*') THEN 'TRANSLATION_TRAP'
            WHEN REGEXP_LIKE(TXT2,'.* (MINDED|TRAINING PROGRAM) .*') THEN 'CEO_MINDED_TRAINING'
            WHEN REGEXP_LIKE(TXT2,'.* (HOTEL|RESORT|INN|SUITES|MOTEL|COMMONS|TOWERS|PLAZA|APARTMENTS|CONDOMINIUM|PRUDENTE|ABRAHAM) .*') THEN 'PLACE_PROPERTY'
            WHEN REGEXP_LIKE(TXT2,'.* (FIELD CTO|FIELD CISO|CLIENT CTO|CLIENT CIO|CLIENT PRESIDENT|VIRTUAL CIO|VIRTUAL CTO) .*') THEN 'SCOPED_CXO_POLICY'
            ELSE NULL
        END AS EXCLUSION_REASON
    FROM s
)
SELECT e.* EXCLUDE (TXT2, RAW2),
    (EXCLUSION_REASON IS NULL) AS KEEP_FLAG,
    ROLE_TIER AS PRIMARY_ROLE_TIER
FROM e
), ranked AS (
    SELECT hp.*,
        (COUNT(*) OVER (PARTITION BY CANONICAL_JOB_ID) > 1) AS IS_CROSS_TIER,
        ROW_NUMBER() OVER (PARTITION BY CANONICAL_JOB_ID ORDER BY ROLE_TIER) AS rn
    FROM high_precision hp
    WHERE KEEP_FLAG
)
SELECT * EXCLUDE (rn)
FROM ranked
WHERE rn = 1;

